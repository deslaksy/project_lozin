#Дан список A размера N. Сформировать два новых списка B и C: в список B записатьвсе положительные элементы список A, в список C — все отрицательные (сохраняяисходный порядок следования элементов). Вывести вначале размер и содержимоесписка B, а затем — размер и содержимое списка C.
A = list(map(int, input("Введите элементы списка через пробел: ").split()))
B = [x for x in A if x > 0]
C = [x for x in A if x < 0]
print("Список B (положительные):", len(B), "элементов:", B)
print("Список C (отрицательные):", len(C), "элементов:", C)
    
